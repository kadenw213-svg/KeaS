// Generates hub/lib/confusables.mjs from Unicode's confusables.txt (UTS #39):
//   node scripts/gen-confusables.mjs <path to confusables.txt>
// Download it from https://www.unicode.org/Public/security/latest/confusables.txt first (it isn't kept in the repo).
//
// Kept: every single-code-point source (not ASCII) whose prototype, after compatibility decomposition, dropping
// accents and lower-casing, is one to three ASCII letters or digits. Lower-case forms of the sources are added too,
// so the map works before or after lower-casing (Cherokee and Armenian have case pairs the table lists once).
// A few prototypes are themselves non-ASCII letters (kra, dotless i, ...); PROTOTYPES says which ASCII letter they pass for.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/gen-confusables.mjs <confusables.txt>'); process.exit(1); }
const text = readFileSync(src, 'utf8');
const version = /^#\s*Version:\s*(\S+)/m.exec(text)?.[1] ?? 'unknown';
const date = /^#\s*Date:\s*([^\r\n]+)/m.exec(text)?.[1]?.trim() ?? 'unknown';

const PROTOTYPES = { 'ĸ': 'k', 'ı': 'i', 'ȷ': 'j', 'ʀ': 'r', 'ɪ': 'i', 'ʏ': 'y', 'ɴ': 'n', 'ʟ': 'l', 'ʜ': 'h', 'ɢ': 'g', 'ß': 'b', 'ø': 'o', 'đ': 'd', 'ħ': 'h', 'ł': 'l', 'ŧ': 't' };
const plain = (s) => [...s.normalize('NFKD').replace(/\p{M}/gu, '').toLowerCase()].map((c) => PROTOTYPES[c] ?? c).join('');

const map = new Map();
for (const line of text.split(/\r?\n/)) {
  const m = /^([0-9A-F]+)\s*;\s*([0-9A-F ]+?)\s*;/.exec(line);
  if (!m) continue;
  const s = String.fromCodePoint(parseInt(m[1], 16));
  if (s.codePointAt(0) < 0x80) continue; // ASCII look-alikes (rn, vv, 0/1) are folded in names.mjs itself
  const target = plain(m[2].split(' ').map((h) => String.fromCodePoint(parseInt(h, 16))).join(''));
  if (!/^[a-z0-9]{1,3}$/.test(target)) continue;
  for (const form of new Set([s, s.toLowerCase(), s.normalize('NFKD').replace(/\p{M}/gu, '')])) {
    if ([...form].length !== 1 || form.codePointAt(0) < 0x80) continue;
    if (plain(form) === target) continue; // decomposition alone already gets there
    if (!map.has(form)) map.set(form, target);
  }
}
for (const [c, t] of Object.entries(PROTOTYPES)) if (!map.has(c)) map.set(c, t);

// Grouped by target: { a: 'chars that pass for a', ... }, written with \u escapes so the file is plain ASCII.
const groups = {};
for (const [c, t] of [...map].sort((a, b) => a[0].codePointAt(0) - b[0].codePointAt(0))) (groups[t] ||= []).push(c);
const esc = (s) => [...s].map((c) => { const cp = c.codePointAt(0); return cp > 0xffff ? `\\u{${cp.toString(16)}}` : `\\u${cp.toString(16).padStart(4, '0')}`; }).join('');
const body = Object.keys(groups).sort().map((t) => `  ${/^[a-z]\w*$/.test(t) ? t : `'${t}'`}: '${esc(groups[t].join(''))}',`).join('\n');
const out = `// GENERATED by scripts/gen-confusables.mjs from Unicode confusables.txt (UTS #39), version ${version}, ${date}.
// Don't edit by hand: rerun the script with a newer confusables.txt. ${map.size} characters that pass for ASCII letters
// and digits (Cyrillic, Greek, Armenian, Cherokee, Lisu, small capitals, IPA and Latin extended, mathematical letters, ...).
// Source data: Unicode, Inc. (https://www.unicode.org/terms_of_use.html).

const GROUPS = {
${body}
};

/** Character -> the ASCII letters or digits it passes for. */
export const CONFUSABLES = new Map(Object.entries(GROUPS).flatMap(([t, chars]) => [...chars].map((c) => [c, t])));
`;
const dest = join(dirname(fileURLToPath(import.meta.url)), '..', 'hub', 'lib', 'confusables.mjs');
writeFileSync(dest, out);
console.log(`wrote ${dest}: ${map.size} characters, Unicode ${version}`);
